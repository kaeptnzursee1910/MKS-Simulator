import { add, mul, pow, sin, cos, diff, simplify, expand, sym, num, sqrtsimp, series } from '../js/cas/expr.js';
import { tex } from '../js/cas/latex.js';
import { parse } from '../js/cas/parse.js';
let fails=0; const eq=(a,b,msg)=>{ if(a!==b){fails++;console.log('FAIL',msg,'\n  got',a,'\n  exp',b)} else console.log('ok',msg) };
