eq(tex(parse('k/m')), '\\frac{k}{m}', 'frac');
eq(tex(parse('J_2 + 4 m r^2')), 'J_{2} + 4 m r^{2}', 'J');
eq(tex(sin(parse('-x'))), '-\\sin x', 'sin odd');
